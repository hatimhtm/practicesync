'use strict';

/*
 * Generates the app icon (build/icon-1024.png) and the monochrome menu-bar
 * (tray) template icon (src/main/trayIcon.js, base64) by rendering crisp SVG in
 * headless Chrome. Run with:  node build/make-icon.js
 * Then `npm run icon` compiles icon-1024.png → icon.icns.
 */

const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright-core');

const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';

// A clean "sync" mark (two curved arrows) — the Lucide refresh-cw glyph, in a
// 24×24 coordinate space. Stroked, round caps/joins.
const SYNC = `
  <path d="M3 12a9 9 0 0 1 9-9 9.75 9.75 0 0 1 6.74 2.74L21 8" />
  <path d="M21 3v5h-5" />
  <path d="M21 12a9 9 0 0 1-9 9 9.75 9.75 0 0 1-6.74-2.74L3 16" />
  <path d="M3 21v-5h5" />`;

// App icon: full-bleed rounded square, blue→indigo gradient, soft top sheen, a
// white health "+" centered inside the white sync ring.
function appSvg() {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
    <defs>
      <linearGradient id="g" x1="0" y1="0" x2="0" y2="1">
        <stop offset="0" stop-color="#4f8bff"/>
        <stop offset="0.55" stop-color="#5566f5"/>
        <stop offset="1" stop-color="#7a3df0"/>
      </linearGradient>
      <radialGradient id="sheen" cx="0.3" cy="0.12" r="0.9">
        <stop offset="0" stop-color="#ffffff" stop-opacity="0.30"/>
        <stop offset="0.5" stop-color="#ffffff" stop-opacity="0"/>
      </radialGradient>
      <filter id="ds" x="-20%" y="-20%" width="140%" height="140%">
        <feDropShadow dx="0" dy="14" stdDeviation="18" flood-color="#0a1330" flood-opacity="0.35"/>
      </filter>
    </defs>
    <rect x="0" y="0" width="1024" height="1024" rx="228" fill="url(#g)"/>
    <rect x="0" y="0" width="1024" height="1024" rx="228" fill="url(#sheen)"/>
    <g filter="url(#ds)">
      <g transform="translate(512 512) scale(20.5) translate(-12 -12)"
         fill="none" stroke="#ffffff" stroke-width="2.1" stroke-linecap="round" stroke-linejoin="round">
        ${SYNC}
      </g>
      <g transform="translate(512 512)" fill="#ffffff">
        <rect x="-26" y="-86" width="52" height="172" rx="22"/>
        <rect x="-86" y="-26" width="172" height="52" rx="22"/>
      </g>
    </g>
  </svg>`;
}

// Tray glyph: monochrome (black + alpha) so macOS can tint it for light/dark
// menu bars. Just the sync mark, a touch bolder for small sizes.
function traySvg(size) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24"
      fill="none" stroke="#000000" stroke-width="2.3" stroke-linecap="round" stroke-linejoin="round">
    ${SYNC}
  </svg>`;
}

async function shoot(page, svg, w, h, out) {
  await page.setViewportSize({ width: w, height: h });
  await page.setContent(`<!doctype html><html><body style="margin:0">${svg}</body></html>`);
  const el = await page.$('svg');
  await el.screenshot({ path: out, omitBackground: true });
}

(async () => {
  let browser;
  try { browser = await chromium.launch({ channel: 'chrome', headless: true }); }
  catch { browser = await chromium.launch({ executablePath: CHROME, headless: true }); }
  const page = await browser.newPage();

  const iconPath = path.join(__dirname, 'icon-1024.png');
  await shoot(page, appSvg(), 1024, 1024, iconPath);
  console.log('wrote', iconPath);

  // Tray @2x (44px) — embed as base64 so it ships with the packaged app.
  const trayPath = path.join(__dirname, 'tray-2x.png');
  await shoot(page, traySvg(44), 44, 44, trayPath);
  const b64 = fs.readFileSync(trayPath).toString('base64');
  fs.unlinkSync(trayPath);
  const mod = `'use strict';\n// Auto-generated by build/make-icon.js — monochrome menu-bar (template) icon, 44px (@2x of 22pt).\nmodule.exports = '${b64}';\n`;
  fs.writeFileSync(path.join(__dirname, '..', 'src', 'main', 'trayIcon.js'), mod);
  console.log('wrote src/main/trayIcon.js (', b64.length, 'b64 chars )');

  await browser.close();
})();
